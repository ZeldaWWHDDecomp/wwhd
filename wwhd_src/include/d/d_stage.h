// HD: copy the actor base in integer words, preserving NaNs and interleaved load/store order.
struct dStage_actorBaseWords {
    be<u32> parameters;
    be<u32> position[3];
    be<u32> angleAndSetID[2];
};
WWHD_SIZE(dStage_actorBaseWords, sizeof(fopAcM_prmBase_class));
static inline void dStage_copyActorBase(u32 destination, u32 source) {
    dStage_actorBaseWords* dst = gabi::at<dStage_actorBaseWords>(destination);
    dStage_actorBaseWords* src = gabi::at<dStage_actorBaseWords>(source);
    dst->parameters = src->parameters;
    dst->position[0] = src->position[0];
    dst->position[1] = src->position[1];
    dst->position[2] = src->position[2];
    dst->angleAndSetID[0] = src->angleAndSetID[0];
    dst->angleAndSetID[1] = src->angleAndSetID[1];
}
