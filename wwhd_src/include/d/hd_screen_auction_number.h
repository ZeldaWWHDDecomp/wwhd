/* HD-only rolling auction digit screen and state descriptors. */
#pragma once
#include "bindings.h"
struct HdAuctionAction { gptr<gfn> mVtable; };
struct HdAuctionStateMachine { gptr<gfn> mVtable; };
struct HdAuctionStateDelegate { be<u16> mAdjust, mSlot; be<u32> mKind; };
struct HdAuctionState {
    be<u32> mID; gptr<void> mName; gptr<void> mVtable;
    HdAuctionStateDelegate mInit, mMove, mExit;
    be<u16> mEmptyAdjust, mEmptySlot;
    be<u32> mFlags; gptr<void> mpParent;
};
struct HdAuctionSafeString { gptr<void> mpString; gptr<void> mVtable; };
struct HdAuctionNames { HdAuctionSafeString mNames[2]; };
struct HdAuctionLayout { u8 padding[0xD4]; gptr<void> mpAnimation; u8 padding2[8]; gptr<gfn> mVtable; u8 padding3[0x2C]; };
struct HdAuctionNumber {
    u8 padding[4]; gptr<void> mVtable;
    u8 padding2[0x10]; gptr<HdAuctionStateMachine> mpStateMachine;
    u8 padding3[4]; gptr<HdAuctionAction> mpCurrentAction;
    u8 padding4[8]; gptr<void> mMemberVtable, mSecondaryVtable;
    u8 padding5[0x10]; gptr<HdAuctionLayout> mpLayout;
    u8 padding6[8]; be<u32> mRollFrame;
    be<s16> mShownDigit, mTargetDigit;
    be<u8> mRollingUp; u8 padding7[3];
    void rollInit();
    void rollMove();
    u32 setup(u32, u32, u32);
    void setDigit(u32);
    void roll(u32, u32, u32);
    u32 loadScreen(u32, u32, u32, u32, u32);
};
struct HdAuctionHeapOwner { u8 padding[0x10]; gptr<void> mpHeap; };
struct HdAuctionHeapPointer { gptr<HdAuctionHeapOwner> mpOwner; };
struct HdAuctionGlobals { be<u32> mFirst, mSecond, mThird, mFourth; };
struct HdAuctionRange { be<f32> mLower, mUpper; be<u8> mSignedInitialized, mUnsignedInitialized; };
struct HdAuctionRegistration { u8 bytes[12]; };
