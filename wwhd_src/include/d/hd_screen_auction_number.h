WWHD_SIZE(HdAuctionSafeString, 8);
WWHD_SIZE(HdAuctionNames, 16);
WWHD_SIZE(HdAuctionLayout, 0x110);
WWHD_OFFSET(HdAuctionLayout, mVtable, 0xE0);
WWHD_OFFSET(HdAuctionNumber, mpStateMachine, 0x18);
WWHD_OFFSET(HdAuctionNumber, mpCurrentAction, 0x20);
WWHD_OFFSET(HdAuctionNumber, mpLayout, 0x44);
WWHD_OFFSET(HdAuctionNumber, mRollFrame, 0x50);
WWHD_SIZE(HdAuctionNumber, 0x5C);
WWHD_SIZE(HdAuctionHeapOwner, 0x14);
WWHD_SIZE(HdAuctionHeapPointer, 4);
