struct hdMsgEvent_window_c {
    u8 _000[0x18];
    /* 0x018 */ hdMsgEvent_stateMachine_c mStateMachine;
    u8 _019[0x48-0x19];
    /* 0x048 */ be<u32> mPaneCount;
    /* 0x04C */ gptr<gptr<hdMsgEvent_pane_c>> mpPanes;
    u8 _050[4];
    /* 0x054 */ be<u32> mInputFlags;
    u8 _058[4];
    /* 0x05C */ be<u32> mMessageId;
    u8 _060[8];
    /* 0x068 */ gptr<hdMsgEvent_pane_c> mpTextPane;
    u8 _06C[0x84-0x6C];
    /* 0x084 */ be<u32> mAdvanceCount;
    u8 _088[8];
    /* 0x090 */ be<u32> mShownCharacters;
    u8 _094[0xC0-0x94];
    /* 0x0C0 */ be<u32> mStopPoints[10];
    /* 0x0E8 */ be<u32> mStopIndex;
    u8 _0EC[0x118-0xEC];
    /* 0x118 */ gptr<hdMsgEvent_message_c> mpMessage;
    /* 0x11C */ be<u32> mWindowType;
    u8 _120[0x190-0x120];
    /* 0x190 */ be<u32> mFrame;
    /* 0x194 */ be<u32> mBeatAges[6];
    /* 0x1AC */ be<u32> mProgress;
    /* 0x1B0 */ be<u32> mSong;
    /* 0x1B4 */ be<u32> mBeatCount;
    /* 0x1B8 */ be<u32> mDisplayCount;
    /* 0x1BC */ be<u32> mPaneRow;
    /* 0x1C0 */ be<u32> mBeatTimes[7];
    /* 0x1DC */ be<u32> mCompleted;
    /* 0x1E0 */ be<u32> mInputRow;
    /* 0x1E4 */ be<u32> mShownPaneCount;
    /* 0x1E8 */ be<u8> mAdvanceRequested;
    u8 _1E9[3];
    /* 0x1EC */ be<u32> mInputDelay;
    // HD: all out-of-range array accesses fall back to element zero.
    be<u32>& beatTime(u32 index) { return mBeatTimes[index < 7 ? index : 0]; }
    be<u32>& beatAge(u32 index) { return mBeatAges[index < 6 ? index : 0]; }
    be<u32>& stopPoint(u32 index) { return mStopPoints[index < 10 ? index : 0]; }
    hdMsgEvent_pane_c* pane(u32 index) { return mpPanes[index < mPaneCount ? index : 0]; }
    u32 lengthIndex(s32 index);
    u32 paneIndex(s32 row, s32 column);
    void resetPane(u32 index);
    void enterWait();
    void initializeBeats();
    void showPane(u32 index);
    void updateBeatDisplay();
    void updateShortWait();
    u32 inputReady();
    void hidePane(u32 index);
    void playEventSound(u32 alternate);
    void updateSequence();
    void updateTyping();
    void updateCloseWait();
    void advanceStopPoint();
    void updateInput();
};
