inline void Hha_removeSplash(daObjHhaSplash_c* splash) {
    u32 target = Hha_guest<HhaSplashVtable>(splash->mSplashCb.mVtable)->mRemove;
    gabi::call(target, gabi::ea(splash));
}
// HD: direct and virtual GHS descriptors keep the audited raw-call harness convention.
inline void Hha_dispatch(daObjHhaPart_c* part, daObjHha_c* parent,
                         const gabi::ptmf<daObjHhaPart_c::daObjHhaPartCallBack>& member) {
    s16 slot = member.i;
    if (slot) {
        u32 receiver = gabi::ea(part) + (s32)(s16)member.d, target;
        if (slot < 0) target = member.f;
        else {
            s16 offset = reinterpret_cast<const be<s16>*>(&member.f)[1];
            u32 table = *Hha_guest<be<u32>>(receiver + (s32)offset);
            target = *Hha_guest<be<u32>>(table + (u32)slot * 8 + 4);
        }
        gabi::call(target, receiver, gabi::ea(parent));
    }
}
