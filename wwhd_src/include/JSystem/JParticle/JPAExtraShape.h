 f32 getScaleInValueY();
 u8 getAnmTypeX();
 u8 getAnmTypeY();
 s32 getAnmCycleX();
 s32 getAnmCycleY();
 f32 getIncreaseRateX();
 f32 getIncreaseRateY();
 f32 getDecreaseRateX();
 f32 getDecreaseRateY();
 u8 getPivotX();
 u8 getPivotY();
 f32 getRandomScale();
 u32 isEnableAlpha();
 u32 isEnableSinWave();
 f32 getAlphaInTiming();
 f32 getAlphaOutTiming();
 f32 getAlphaInValue();
 f32 getAlphaBaseValue();
 u8 getAlphaWaveType();
 f32 getAlphaWaveParam1();
 f32 getAlphaWaveParam2();
