    void buildFrustumMatrix(ProjectionMatrix*) const;
    void projectPoint(ViewVector*,const ViewVector*);
    void projectToViewport(ViewVector*,const ViewVector*,const ViewportBounds*);
    void update();
    ProjectionMatrix* projection();
    ProjectionMatrix* deviceProjection();
