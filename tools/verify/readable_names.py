#!/usr/bin/env python3
"""Readability pass for verified sources (step 1: named calls).

usage: readable_names.py [--root ROOT] [--dry-run] SOURCE.cpp ...
       readable_names.py --all          (regenerate wwhd_src/include/fn_names.h for every named address)

fn_names.h already holds every name of build/names.tsv, so running this on a source only
rewrites the source (the header does not change and never conflicts between parallel rewrites). Names from the map are
matcher hypotheses: the final GameCube-style unit calls through gc_api / bindings (types checked by the harness),
fn:: calls are the mechanical intermediate step.

Replaces calls by address,

    gabi::call<u32>(0x025200D4)            gabi::call(0x02543280, manager, staff)

with calls by name from the function map (build/names.tsv),

    fn::dComIfGp_getEvent<u32>()           fn::dEvent_manager_c_cutEnd(manager, staff)

The names live in wwhd_src/include/fn_names.h as thin wrappers,

    template <class R = void, class... A> inline R NAME(A... a) { return gabi::call<R>(0xADDR, a...); }

so the call the harness sees is exactly the same (same address, same argument types and values):
the unit still verifies unchanged. Addresses without a name in the map stay as they are.
Re-run verify.py on the unit afterwards; the harness proves nothing changed.

Later steps (not here yet): struct fields for raw offsets, named data symbols, folding the
WWHD_FUNC/VERIFY scaffolding into one line.
"""
import argparse
import os
import re
import sys

OPS = {"__pl": "op_add", "__mi": "op_sub", "__ml": "op_mul", "__dv": "op_div", "__eq": "op_eq",
       "__ne": "op_ne", "__as": "op_assign", "__apl": "op_add_assign", "__ami": "op_sub_assign",
       "__amu": "op_mul_assign", "__adv": "op_div_assign", "__ct": "ctor", "__dt": "dtor",
       "__vc": "op_index", "__cl": "op_call", "__ng": "op_neg", "__dl": "op_delete", "__nw": "op_new", "__dla": "op_delete_array", "__nwa": "op_new_array"}

CALL = re.compile(r"gabi::call(<[^()]*?>)?\(\s*0x([0-9A-Fa-f]{8})u?\s*(,\s*|\))")


def ident(name):
    name = re.sub(r"<[^<>]*>", "", name)          # template arguments
    parts = name.split("::")
    if parts and parts[-1].startswith("~"):
        parts[-1] = "dtor"
    parts = [OPS.get(p, p) for p in parts]
    s = "_".join(parts)
    s = re.sub(r"[^0-9A-Za-z_]", "_", s)
    s = re.sub(r"_+", "_", s).strip("_")
    if not s or s[0].isdigit():
        s = "f_" + s
    return s


def load_names(path):
    names = {}
    for line in open(path):
        f = line.rstrip("\n").split("\t")
        if len(f) >= 2 and re.fullmatch(r"[0-9A-Fa-f]{8}", f[0]) and f[1] and f[1] != "?":
            names[int(f[0], 16)] = f[1]
    return names


def load_header(path):
    """existing fn_names.h: address -> identifier"""
    have = {}
    if os.path.exists(path):
        for m in re.finditer(r"inline R (\w+)\(A\.\.\. a\) \{ return gabi::call<R>\(0x([0-9A-F]{8}), a\.\.\.\); \}",
                             open(path).read()):
            have[int(m.group(2), 16)] = m.group(1)
    return have


def write_header(path, have, names):
    lines = ["/* Named calls (generated by tools/verify/readable_names.py --all from build/names.tsv; do not edit).",
             " * Each name is a thin wrapper: the harness sees the same call by address. */",
             "#pragma once", '#include "wwhd.h"', "", "namespace fn {"]
    for addr in sorted(have, key=lambda a: have[a]):
        lines.append("template <class R = void, class... A> inline R %s(A... a) { return gabi::call<R>(0x%08X, a...); }"
                     "  // %s" % (have[addr], addr, names.get(addr, "")))
    lines += ["}  // namespace fn", ""]
    open(path, "w").write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("sources", nargs="*")
    a = ap.parse_args()
    names = load_names(os.path.join(a.root, "build", "names.tsv"))
    hdr = os.path.join(a.root, "wwhd_src", "include", "fn_names.h")
    have = load_header(hdr)
    used_ids = {v: k for k, v in have.items()}
    if a.all:
        for addr in sorted(names):
            if addr not in have:
                base = ident(names[addr])
                nid, k = base, 2
                while nid in used_ids and used_ids[nid] != addr:
                    nid = "%s_%d" % (base, k)
                    k += 1
                have[addr] = nid
                used_ids[nid] = addr
        write_header(hdr, have, names)
        print("fn_names.h: %d names" % len(have))
        return
    total = renamed = 0
    for src in a.sources:
        text = open(src).read()

        def sub(m):
            nonlocal total, renamed
            total += 1
            addr = int(m.group(2), 16)
            if addr not in names:
                return m.group(0)
            if addr not in have:
                base = ident(names[addr])
                nid, k = base, 2
                while nid in used_ids and used_ids[nid] != addr:
                    nid = "%s_%d" % (base, k)
                    k += 1
                have[addr] = nid
                used_ids[nid] = addr
            renamed += 1
            tmpl = m.group(1) or ""
            return "fn::%s%s(%s" % (have[addr], tmpl, ")" if m.group(3) == ")" else "")

        new = CALL.sub(sub, text)
        if new != text and '#include "fn_names.h"' not in new:
            first = new.find("#include")
            eol = new.find("\n", first) + 1
            new = new[:eol] + '#include "fn_names.h"\n' + new[eol:]
        if not a.dry_run and new != text:
            open(src, "w").write(new)
    if not a.dry_run:
        write_header(hdr, have, names)
    print("calls by address: %d, now named: %d, left (no name in the map): %d" % (total, renamed, total - renamed))


if __name__ == "__main__":
    main()
