#!/usr/bin/env python3
"""Self-test: a whole-form run nested inside another (wwhd_src/include/d/t60_whole.h, the depth counter) leaves the
outer run's state alone.

The whole form keeps process-wide flags for the run in progress (s_whole, s_prevDt; 2026-11-19, the t60 statics
lint). A Guard that begins inside the tick30 step's whole run runs at dt 1 (an actor fast-created and executed from
another's execute): its begin takes the !on() path. Before the depth counter that path cleared s_whole, so the outer
run's end skipped dt and its latch. Now the nested Guard counts one level (s_depth) and its end pops only that level.

Test actor: d_a_mtoge daMtoge_actionUp 021E01B8 in the whole form; after its skip it opens a second Guard on the same
actor (the nested run) and records whether the outer flag survived it: current.pos.z += 100 when s_whole changed.
At N = 1 (the reference) no Guard is active, so the flag never changes; the N = 2 tick30 step must match.
 1. the header as it is: T-02 N = 2 passes (the nested Guard leaves the outer run's flag alone);
 2. negative: the header without the nested branch (the old !on() reset) fails T-02.
Temporary files go to tools/verify/units/_t60_test/ (removed at the end). Exit 0 when both pass.
"""
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
UNITS = os.path.join(HERE, "units")
TMP = os.path.join(UNITS, "_t60_test")
SRC = "wwhd_src/d/actor/d_a_mtoge.cpp"
HDR = os.path.join(ROOT, "wwhd_src", "include", "d", "t60_whole.h")
FUNC = "021E01B8"
N = os.environ.get("T60_TEST_N", "2000")
SEED = os.environ.get("T60_TEST_SEED", "1")
KEY = "if (s_whole && s_wholeStep == t60_step_counter()) { /* nested"
OLD = "if (false) { /* nested"

HEAD = "/* 021E01B8 */\nBOOL daMtoge_actionUp(daMtoge_c* i_this) {\n"
WHOLE = """namespace t60wn {
static void get(daMtoge_c* a, f32* v) { v[0] = a->current.pos.x; }
static void set(daMtoge_c* a, const f32* v) { a->current.pos.x = v[0]; }
static void mtx(daMtoge_c*) {}
static bool held(daMtoge_c*) { return false; }
static const t60w::Ops<daMtoge_c> kOps = {1, 1, get, set, mtx, held};
}
/* 021E01B8 */
BOOL daMtoge_actionUp(daMtoge_c* i_this) {
    t60w::Guard<daMtoge_c> g(i_this, t60wn::kOps);
    if (g.skip)
        return TRUE;
    g.model = true;
    const bool outer = t60w::s_whole;
    {
        t60w::Guard<daMtoge_c> nested(i_this, t60wn::kOps); /* a run nested inside this one (at dt 1: the !on() path) */
        if (!nested.skip)
            i_this->current.pos.x += 1.0f;
    }
    if (t60w::s_whole != outer)
        i_this->current.pos.z += 100.0f; /* the nested run changed the outer run's state */
"""
SPEC = ["# GENERATED by t60whole_nested_test.py",
        "src %s",
        "field 021E01B8 r3+0x4 u32 7        # the process id",
        "t60conv 021E01B8",
        "t60nocmp 021E01B8                  # the test variant differs from the original by design (T-02 only)"]


def write(name, header):
    text = open(os.path.join(ROOT, SRC)).read()
    assert HEAD in text, "d_a_mtoge.cpp changed: update t60whole_nested_test.py"
    text = text.replace(HEAD, WHOLE, 1).replace('#include "d/actor/d_a_mtoge.h"\n',
                                                '#include "d/actor/d_a_mtoge.h"\n#include "%s"\n' % header, 1)
    src = os.path.join(TMP, name + ".cpp")
    open(src, "w").write(text)
    open(os.path.join(TMP, name + ".txt"), "w").write("\n".join(SPEC) % os.path.relpath(src, ROOT) + "\n")


def run(name):
    cmd = [sys.executable, os.path.join(HERE, "verify.py"), "_t60_test/" + name, "-n", N, "-shards", "1", "--no-cache",
           "-only", FUNC, "-seed", SEED, "-t60steps", "2"]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    row = [l for l in r.stdout.splitlines() if re.match(r"^%s  " % FUNC, l)]
    return r.returncode, (row[0] if row else ""), r.stdout + r.stderr


def main():
    os.makedirs(TMP, exist_ok=True)
    fails = []
    try:
        hdr = open(HDR).read()
        assert KEY in hdr, "t60_whole.h has no nested branch: update t60whole_nested_test.py"
        old = os.path.join(TMP, "t60_whole_nonest.h")
        open(old, "w").write(hdr.replace(KEY, OLD))
        write("wnest_depth", "d/t60_whole.h")
        write("wnest_old", old)
        rc, row, out = run("wnest_depth")
        if rc != 0 or not row.rstrip().endswith("ok"):
            fails.append("1. nested whole run with the depth counter: rc %d, row %r\n%s" % (rc, row, out[-3000:]))
        else:
            print("ok   1. nested whole run: the outer run's state survives, T-02 N 2 passes (%s)" % row.split()[1:4])
        rc, row, out = run("wnest_old")
        if rc == 0 and row.rstrip().endswith("ok"):
            fails.append("2. negative (no nested branch) passed T-02: the reset is not reproduced\n%s" % row)
        elif not row:
            fails.append("2. negative: no row (rc %d)\n%s" % (rc, out[-3000:]))
        else:
            print("ok   2. negative: the old !on() reset clears the outer run (fails as it should: %s)" % re.sub(r"\s+", " ", row)[-170:])
    finally:
        for f in os.listdir(TMP) if os.path.isdir(TMP) else []:
            if f.startswith(("wnest_", "t60_whole_nonest")):
                os.remove(os.path.join(TMP, f))
        sys.path.insert(0, HERE)
        import verify  # noqa: E402
        for nm in ("wnest_depth", "wnest_old"):  # this test's own unit build dirs
            for d in verify.unit_dirs_all("_t60_test/" + nm):
                shutil.rmtree(d, ignore_errors=True)
        if os.path.isdir(TMP) and not os.listdir(TMP):
            os.rmdir(TMP)
    for f in fails:
        print("FAIL " + f)
    print("t60whole_nested_test: %s" % ("FAIL" if fails else "PASS"))
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
