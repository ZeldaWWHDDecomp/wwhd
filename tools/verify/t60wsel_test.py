#!/usr/bin/env python3
"""Self-test: the mixed whole form's call check (`t60wcalls` + `t60wsel`, verify harness; 2026-11-19).

A mixed form runs some frames whole through t60w::Guard (first case d_a_nz: frames that start in the damage / bomb
action) and every other frame per step. The whole-form call check (as many calls over the N steps as in the one step)
holds only on the Guard frames; a per-step frame repeats its calls on every step by design. `t60wcalls ADDR...` are
counted like `t60calls` but compared only on the inputs whose frame-start value at the `t60wsel FUNC rN+OFF TYPE V,...`
selector is listed.

Test actor: d_a_mtoge daMtoge_actionUp 021E01B8, rewritten as a mixed form: mAction (r3+0x3BC) 1 runs whole (Guard,
dBgW::Move 024F43DC once on the tick30 step), any other action per step (dBgW::Move on every step). Inputs: mAction 0 or 1.
 1. `t60wcalls 024F43DC` + `t60wsel 021E01B8 r3+0x3BC u8 1`: T-02 N 2 passes;
 2. the same address as plain `t60calls` (no selector): fails (the per-step inputs call it twice over the two steps);
 3. negative control (the Guard path off, as T60C_NEGCTRL does) with spec 1: fails (the selected inputs are checked).
Temporary files go to tools/verify/units/_t60_test/ (removed at the end). Exit 0 when all three behave.
"""
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
UNITS = os.path.join(HERE, "units")
TMP = os.path.join(UNITS, "_t60_test")
SRC = "wwhd_src/d/actor/d_a_mtoge.cpp"
FUNC = "021E01B8"
N = os.environ.get("T60_TEST_N", "2000")
SEED = os.environ.get("T60_TEST_SEED", "1")

HEAD = "/* 021E01B8 */\nBOOL daMtoge_actionUp(daMtoge_c* i_this) {\n"
MIXED = """namespace t60wt {
static void get(daMtoge_c* a, f32* v) { v[0] = a->current.pos.x; }
static void set(daMtoge_c* a, const f32* v) { a->current.pos.x = v[0]; }
static void mtx(daMtoge_c*) {}
static bool held(daMtoge_c*) { return false; }
static const t60w::Ops<daMtoge_c> kOps = {1, 1, get, set, mtx, held};
}
/* 021E01B8 */
BOOL daMtoge_actionUp(daMtoge_c* i_this) {
    if (%s && i_this->mAction == 1) { /* the mixed form: action 1 frames run whole */
        t60w::Guard<daMtoge_c> g(i_this, t60wt::kOps);
        if (g.skip)
            return TRUE;
        g.model = true;
        dBgW_Move(i_this->mpBgW);
        return TRUE;
    }
    dBgW_Move(i_this->mpBgW); /* per step */
    return TRUE;
}
static BOOL wsel_unused_original(daMtoge_c* i_this) {
"""
SPEC = ["# GENERATED by t60wsel_test.py",
        "src %s",
        "field 021E01B8 r3+0x3BC u8 0,1     # mAction: 1 = the whole-form frames",
        "field 021E01B8 r3+0x4 u32 7        # the process id",
        "t60conv 021E01B8",
        "t60nocmp 021E01B8                  # the test variant differs from the original by design (T-02 only)"]
SEL = ["t60wcalls 024F43DC", "t60wsel 021E01B8 r3+0x3BC u8 1"]
PLAIN = ["t60calls 024F43DC"]


def write(name, cond, extra):
    text = open(os.path.join(ROOT, SRC)).read()
    assert HEAD in text, "d_a_mtoge.cpp changed: update t60wsel_test.py"
    text = text.replace(HEAD, MIXED % cond, 1).replace('#include "d/actor/d_a_mtoge.h"\n',
                                                       '#include "d/actor/d_a_mtoge.h"\n#include "d/t60_whole.h"\n', 1)
    src = os.path.join(TMP, name + ".cpp")
    open(src, "w").write(text)
    open(os.path.join(TMP, name + ".txt"), "w").write("\n".join(SPEC + extra) % os.path.relpath(src, ROOT) + "\n")


def run(name):
    cmd = [sys.executable, os.path.join(HERE, "verify.py"), "_t60_test/" + name, "-n", N, "-shards", "1", "--no-cache",
           "-only", FUNC, "-seed", SEED, "-t60steps", "2"]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    row = [l for l in r.stdout.splitlines() if re.match(r"^%s  " % FUNC, l)]
    return r.returncode, (row[0] if row else ""), r.stdout + r.stderr


NAMES = ("wsel_sel", "wsel_plain", "wsel_nc")


def main():
    os.makedirs(TMP, exist_ok=True)
    fails = []
    try:
        write("wsel_sel", "t60::dt() != 1.0f", SEL)
        write("wsel_plain", "t60::dt() != 1.0f", PLAIN)
        write("wsel_nc", "false", SEL)
        rc, row, out = run("wsel_sel")
        if rc != 0 or not row.rstrip().endswith("ok"):
            fails.append("1. t60wcalls + t60wsel: rc %d, row %r\n%s" % (rc, row, out[-3000:]))
        else:
            print("ok   1. mixed form, t60wcalls + t60wsel: T-02 N 2 passes (%s)" % row.split()[1:4])
        for k, nm, what in ((2, "wsel_plain", "plain t60calls on a mixed form"),
                            (3, "wsel_nc", "negative control (no Guard path) with the selector")):
            rc, row, out = run(nm)
            if not row:
                fails.append("%d. %s: no row (rc %d)\n%s" % (k, what, rc, out[-3000:]))
            elif rc == 0 and row.rstrip().endswith("ok"):
                fails.append("%d. %s passed T-02 (should fail)\n%s" % (k, what, row))
            elif "024F43DC" not in out and "dBgW" not in out:
                fails.append("%d. %s failed, but not on the counted call\n%s" % (k, what, out[-3000:]))
            else:
                print("ok   %d. %s fails as it should (%s)" % (k, what, re.sub(r"\s+", " ", row)[-150:]))
    finally:
        for f in os.listdir(TMP) if os.path.isdir(TMP) else []:
            if f.startswith(NAMES):
                os.remove(os.path.join(TMP, f))
        sys.path.insert(0, HERE)
        import verify  # noqa: E402
        for nm in NAMES:  # this test's own unit build dirs
            for d in verify.unit_dirs_all("_t60_test/" + nm):
                shutil.rmtree(d, ignore_errors=True)
        if os.path.isdir(TMP) and not os.listdir(TMP):
            os.rmdir(TMP)
    for f in fails:
        print("FAIL " + f)
    print("t60wsel_test: %s" % ("FAIL" if fails else "PASS"))
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
