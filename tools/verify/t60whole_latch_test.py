#!/usr/bin/env python3
"""Self-test: whole-form latches (wwhd_src/include/d/t60_whole.h) start fresh for each generated input of T-02.

The whole form keeps a host latch per actor (address + process id) with the previous frame's change; a frame's earlier
steps show the actor moved on by it (set + the picture's matrix step) when the latch says the actor ran in the frame
just before. In T-02 every generated input is one frame; the actor's address and process id repeat across inputs and
the frame tag (g_Counter.mCounter0, a generated word) can be the previous input's + 1, so a picture once ran from the
previous input's latch (gk1 / gp1 / zk1, seed-1 input 1007766). The latch now also needs the step counter (true60.h
) to follow the run that set it by one; the harness advances it by two before an input's first step.

Test actor: d_a_mtoge daMtoge_actionUp 021E01B8 in the whole form (t60w::begin / end) with a picture that shows
current.pos.x and whose matrix step adds 1 to current.pos.y (a stand-in for a matrix step that leaves state behind).
Inputs: process id fixed, frame tag 0 or 1 (the next frame's tag after about every fourth input).
 1. the header as it is: T-02 N = 2 passes (no picture from another input);
 2. negative: the header without the step-counter key fails T-02 (the picture ran from the previous input's latch).
Temporary files go to tools/verify/units/_t60_test/ (removed at the end). Exit 0 when both pass.
"""
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
UNITS = os.path.join(HERE, "units")
TMP = os.path.join(UNITS, "_t60_test")
SRC = "wwhd_src/d/actor/d_a_mtoge.cpp"
HDR = os.path.join(ROOT, "wwhd_src", "include", "d", "t60_whole.h")
FUNC = "021E01B8"
N = os.environ.get("T60_TEST_N", "2000")
SEED = os.environ.get("T60_TEST_SEED", "1")
KEY = " || t60_step_counter() != e->step + 1"

HEAD = "/* 021E01B8 */\nBOOL daMtoge_actionUp(daMtoge_c* i_this) {\n"
WHOLE = """namespace t60wt {
static void get(daMtoge_c* a, f32* v) { v[0] = a->current.pos.x; }
static void set(daMtoge_c* a, const f32* v) { a->current.pos.x = v[0]; }
static void mtx(daMtoge_c* a) { a->current.pos.y += 1.0f; /* a matrix step that leaves state behind */ }
static bool held(daMtoge_c*) { return false; }
static const t60w::Ops<daMtoge_c> kOps = {1, 1, get, set, mtx, held};
}
/* 021E01B8 */
BOOL daMtoge_actionUp(daMtoge_c* i_this) {
    t60w::Guard<daMtoge_c> g(i_this, t60wt::kOps);
    if (g.skip)
        return TRUE;
    g.model = true;
    i_this->current.pos.x += 3.0f; /* the frame's change (the picture's dv) */
"""
SPEC = ["# GENERATED by t60whole_latch_test.py",
        "src %s",
        "field 021E01B8 r3+0x4 u32 7        # the process id: the same actor in every input",
        "field * 101FF558 u32 0,1           # the frame tag: the next frame's tag after some inputs",
        "t60conv 021E01B8",
        "t60nocmp 021E01B8                  # the test variant differs from the original by design (T-02 only)"]


def write(name, header):
    text = open(os.path.join(ROOT, SRC)).read()
    assert HEAD in text, "d_a_mtoge.cpp changed: update t60whole_latch_test.py"
    text = text.replace(HEAD, WHOLE, 1).replace('#include "d/actor/d_a_mtoge.h"\n',
                                                '#include "d/actor/d_a_mtoge.h"\n#include "%s"\n' % header, 1)
    src = os.path.join(TMP, name + ".cpp")
    open(src, "w").write(text)
    open(os.path.join(TMP, name + ".txt"), "w").write("\n".join(SPEC) % os.path.relpath(src, ROOT) + "\n")


def run(name):
    cmd = [sys.executable, os.path.join(HERE, "verify.py"), "_t60_test/" + name, "-n", N, "-shards", "1", "--no-cache",
           "-only", FUNC, "-seed", SEED, "-t60steps", "2"]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    row = [l for l in r.stdout.splitlines() if re.match(r"^%s  " % FUNC, l)]
    return r.returncode, (row[0] if row else ""), r.stdout + r.stderr


def main():
    os.makedirs(TMP, exist_ok=True)
    fails = []
    try:
        hdr = open(HDR).read()
        assert KEY in hdr, "t60_whole.h has no step-counter key: update t60whole_latch_test.py"
        old = os.path.join(TMP, "t60_whole_nokey.h")
        open(old, "w").write(hdr.replace(KEY, ""))
        write("wlatch_key", "d/t60_whole.h")
        write("wlatch_nokey", old)
        rc, row, out = run("wlatch_key")
        if rc != 0 or not row.rstrip().endswith("ok"):
            fails.append("1. whole form with the step-counter key: rc %d, row %r\n%s" % (rc, row, out[-3000:]))
        else:
            print("ok   1. whole-form latch keyed per input: T-02 N 2 passes (%s)" % row.split()[1:4])
        rc, row, out = run("wlatch_nokey")
        if rc == 0 and row.rstrip().endswith("ok"):
            fails.append("2. negative (no step-counter key) passed T-02: the carry-over is not reproduced\n%s" % row)
        elif not row:
            fails.append("2. negative: no row (rc %d)\n%s" % (rc, out[-3000:]))
        else:
            print("ok   2. negative: without the key the picture runs from the previous input's latch (fails as it should: %s)" % re.sub(r"\s+", " ", row)[-170:])
    finally:
        for f in os.listdir(TMP) if os.path.isdir(TMP) else []:
            if f.startswith(("wlatch_", "t60_whole_nokey")):
                os.remove(os.path.join(TMP, f))
        sys.path.insert(0, HERE)
        import verify  # noqa: E402
        for nm in ("wlatch_key", "wlatch_nokey"):  # this test's own unit build dirs
            for d in verify.unit_dirs_all("_t60_test/" + nm):
                shutil.rmtree(d, ignore_errors=True)
        if os.path.isdir(TMP) and not os.listdir(TMP):
            os.rmdir(TMP)
    for f in fails:
        print("FAIL " + f)
    print("t60whole_latch_test: %s" % ("FAIL" if fails else "PASS"))
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
