#!/usr/bin/env python3
"""Self-test: a generated mock called inside a `real` callee (a nested call) writes its declared output storage
(`callee ADDR rN=outSIZE`) from the call's own hash, as a top-level mock does (harness.cpp mock_fill_out).

Before (2026-11-18, objects d_a_obj_shelf / d_a_obj_drift): a nested mock left the out object unwritten, so the
`real` caller read the stale `stackfill` bytes of its own frame. Those depend on the address, and a candidate whose
frame differs from the original's (`t60cand` code, a true60 whole-form wrapper) read another value than the original:
shelf hold_event's fopAcM_SearchByName (r4=out4) found another actor (01 written at another address), drift's
calc_flower_param read other PSMTXMultVec / mtx-to-rot out vectors. The T-02 specs needed `ret! 025D5578 0` and
`real 028E8F64 025F232C` as workarounds.

Test unit: d_a_obj_shelf mode_wait 0238E300 with hold_event 0238E264 `real` + `t60cand` (the original's PowerPC code
on the original side, the candidate's own code on the candidate side) in a test copy of the source whose hold_event
has one more guest Local before the search, so its out object is at another stack address than the original's.
 1. the unit's facts as they are (`callee 025D5578 r4=out4`): T-01 passes (both sides see the same found actor);
 2. negative: the fact as a plain 4-byte pointer (`r4=4`, no output storage, nothing written: the old nested
    behaviour) fails T-01 (the found actor differs with the frame layout).
Temporary files go to tools/verify/units/_t60_test/ (removed at the end). Exit 0 when both pass.
"""
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
UNITS = os.path.join(HERE, "units")
TMP = os.path.join(UNITS, "_t60_test")
SRC = "wwhd_src/d/actor/d_a_obj_shelf.cpp"
BASE = os.path.join(UNITS, "d_a_obj_shelf.txt")
FUNC = "0238E300"
N = os.environ.get("NESTEDOUT_TEST_N", "2000")
SEED = os.environ.get("NESTEDOUT_TEST_SEED", "1")
OUTFACT = "callee 025D5578 r4=out4"

HEAD = "void Act_c::hold_event() {\n    ActorPointer npc;\n"
PADDED = ("void Act_c::hold_event() {\n    gabi::Local<cXyz> nestedout_pad; /* nestedout_test: moves the out object */\n"
          "    (void)nestedout_pad;\n    ActorPointer npc;\n")


def write(name, fact):
    text = open(os.path.join(ROOT, SRC)).read()
    assert HEAD in text, "d_a_obj_shelf.cpp hold_event changed: update nestedout_test.py"
    src = os.path.join(TMP, name + ".cpp")
    open(src, "w").write(text.replace(HEAD, PADDED, 1))
    spec = open(BASE).read()
    assert OUTFACT in spec, "d_a_obj_shelf.txt has no %r: update nestedout_test.py" % OUTFACT
    spec = re.sub(r"^src\s+%s\s*$" % re.escape(SRC), "src " + os.path.relpath(src, ROOT), spec, flags=re.M)
    spec = spec.replace(OUTFACT, fact)
    spec = "# GENERATED by nestedout_test.py\n" + spec + "\nreal 0238E264\nt60cand 0238E264\n"
    open(os.path.join(TMP, name + ".txt"), "w").write(spec)


def run(name):
    cmd = [sys.executable, os.path.join(HERE, "verify.py"), "_t60_test/" + name, "-n", N, "-shards", "1", "--no-cache",
           "-nulltrap", "-only", FUNC, "-seed", SEED]
    r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
    row = [l for l in r.stdout.splitlines() if re.match(r"^%s  " % FUNC, l)]
    return r.returncode, (row[0] if row else ""), r.stdout + r.stderr


def main():
    os.makedirs(TMP, exist_ok=True)
    fails = []
    try:
        write("nestedout_fact", OUTFACT)
        write("nestedout_nofact", "callee 025D5578 r4=4")
        rc, row, out = run("nestedout_fact")
        if rc != 0 or not row.rstrip().endswith("ok"):
            fails.append("1. nested mock with r4=out4: rc %d, row %r\n%s" % (rc, row, out[-3000:]))
        else:
            print("ok   1. nested mock writes its out object: T-01 passes with another frame layout (%s)" % row.split()[-4:-1])
        rc, row, out = run("nestedout_nofact")
        if rc == 0 and row.rstrip().endswith("ok"):
            fails.append("2. negative (no out fact) passed: the frame-layout difference is not reproduced\n%s" % row)
        elif not row:
            fails.append("2. negative: no row (rc %d)\n%s" % (rc, out[-3000:]))
        else:
            print("ok   2. negative: unwritten out object read from the frame differs (fails as it should: %s)" % re.sub(r"\s+", " ", row)[-170:])
    finally:
        for f in os.listdir(TMP) if os.path.isdir(TMP) else []:
            if f.startswith("nestedout_"):
                os.remove(os.path.join(TMP, f))
        sys.path.insert(0, HERE)
        import verify  # noqa: E402
        for nm in ("nestedout_fact", "nestedout_nofact"):  # this test's own unit build dirs
            for d in verify.unit_dirs_all("_t60_test/" + nm):
                shutil.rmtree(d, ignore_errors=True)
        if os.path.isdir(TMP) and not os.listdir(TMP):
            os.rmdir(TMP)
    for f in fails:
        print("FAIL " + f)
    print("nestedout_test: %s" % ("FAIL" if fails else "PASS"))
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
